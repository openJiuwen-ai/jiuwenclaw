"""LLM-based execution accuracy evaluator."""

from jiuwenswarm.symphony.evaluation.evaluators.base import LLMScoreEvaluator


class AccuracyEvaluator(LLMScoreEvaluator):
    metric = "accuracy"
    thresholds = (0.90, 0.95, 0.99)
    aggregation_thresholds = thresholds
    rubric = (
        "准确性二值评分标准：\n"
        "优秀（score=1，满足以下所有条件）：\n"
        "- 无事实性错误，核心信息准确。\n"
        "- 完全符合客观事实，无任何事实性错误。\n"
        "- 逻辑严密，推理严谨，无逻辑谬误。\n"
        "- 符合行业规范/专业规范，表述专业。\n"
        "- 新知识/新产品场景：当回答涉及新知识、新产品、新功能等内容时，"
        "即使评估模型的历史训练数据中未包含这些信息，只要回答逻辑合理、"
        "符合用户需求、表述清晰，也应判断为准确回答。\n"
        "不及格（score=0，满足以下条件之一）：\n"
        "- 存在事实性错误，与客观事实不符。\n"
        "- 存在逻辑谬误，推理过程断裂。\n"
        "- 存在专业偏差，违背行业标准/专业规范。\n"
        "- 输出内容不可用，可能误导用户。\n"
        "补充规则：\n"
        "1. 事实核查：以有无事实错误为首要判断标准，检查执行结果中是否存在"
        "事实性错误。\n"
        "2. 逻辑验证：检查推理过程是否严密，是否存在逻辑谬误。\n"
        "3. 专业规范：评估是否符合行业规范/专业规范。\n"
        "4. 新知识处理：对于涉及新知识、新产品、新功能的内容，评估其逻辑"
        "合理性和表述清晰度。\n"
        "注意事项：如果数据不完整，应在 reason 中说明；核心评估重点是有无"
        "事实错误，只要存在事实性错误即判定为不及格。"
    )
