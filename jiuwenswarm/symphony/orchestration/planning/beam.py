def _required_output_types_from_query(query: str) -> frozenset[str]:
    output_types = set()
    for match in _EXPLICIT_FILE_EXTENSION_RE.finditer(str(query or "")):
        output_type = _output_type_from_extension(match.group(1))
        if output_type:
            output_types.add(output_type)
    return frozenset(output_types)


def _output_type_from_extension(extension: str) -> str | None:
    normalized = str(extension or "").strip().lower().lstrip(".")
    if not normalized:
        return None
    mime_type, _encoding = mimetypes.guess_type(f"file.{normalized}")
    if mime_type in _MIME_TO_OUTPUT_TYPE:
        return _MIME_TO_OUTPUT_TYPE[mime_type]
    if mime_type and mime_type.startswith("image/"):
        return "image"
    return None


