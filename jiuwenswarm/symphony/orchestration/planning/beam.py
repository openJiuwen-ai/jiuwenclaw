def _max_confidence(left: Any, right: Any) -> Any:
    try:
        left_value = float(left)
    except (TypeError, ValueError):
        return right
    try:
        right_value = float(right)
    except (TypeError, ValueError):
        return left
    return max(left_value, right_value)


