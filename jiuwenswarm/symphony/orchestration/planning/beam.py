    async def judge_expansions(
        self,
        query: str,
        expansions: list[NeighborExpansion],
    ) -> dict[str, PlannerJudgement]:
        if not expansions:
            return {}

        first = expansions[0]
        current_skill = self.skill_by_id.get(first.current_skill_id, {})
        payload = {
            "query": query,
            "direction": first.direction,
            "current_skill": self._skill_payload(current_skill),
            "candidates": [
                self._candidate_payload(expansion)
                for expansion in expansions
            ],
        }
        with llm_usage_context("orchestration", "bidirectional_beam_judgement"):
            raw = await self._client().complete_json_async(
                system_prompt=(
                    f"{BEAM_JUDGE_SYSTEM_PROMPT}\n"
                    f"{planner_language_instruction(self.language)}"
                ),
                user_content=json.dumps(payload, ensure_ascii=False),
                error_context="Symphony bidirectional beam judgement",
                request_overrides={
                    "extra_body": {"thinking": {"type": "disabled"}},
                },
            )
        data = json.loads(raw)
        items = data.get("judgements") if isinstance(data, dict) else data
        if not isinstance(items, list):
            return {}

        known_ids = {expansion.candidate_id for expansion in expansions}
        judgements: dict[str, PlannerJudgement] = {}
        for item in items:
            if not isinstance(item, dict):
                continue
            candidate_id = str(item.get("candidate_id") or "").strip()
            if candidate_id not in known_ids:
                continue
            score = _clamp_score(item.get("score"))
            judgements[candidate_id] = PlannerJudgement(
                candidate_id=candidate_id,
                score=score,
                reason=str(item.get("reason") or "").strip(),
            )
        return judgements

    async def _final_rerank_plans(
        self,
        *,
        query: str,
        recommended_plans: list[dict[str, Any]],
        seed_skill_ids: tuple[str, ...],
    ) -> dict[str, Any]:
        base = {
            "enabled": bool(recommended_plans),
            "applied": False,
            "guard_applied": False,
            "guard_reason": "",
            "reason": "",
            "error": "",
            "cross_plan_skill_merge": False,
            "recommended_plans": recommended_plans[: self.effective_top_k],
        }
        if not recommended_plans:
            return base

        prompt_payload = self._final_rerank_payload(
            query=query,
            recommended_plans=recommended_plans,
            seed_skill_ids=seed_skill_ids,
        )
        try:
            with llm_usage_context("orchestration", "beam_final_rerank"):
                raw = await self._client().complete_json_async(
                    system_prompt=(
                        f"{BEAM_FINAL_RERANK_SYSTEM_PROMPT}\n"
                        f"{planner_language_instruction(self.language)}"
                    ),
                    user_content=json.dumps(prompt_payload, ensure_ascii=False),
                    error_context="Symphony beam final rerank",
                    request_overrides={
                        "extra_body": {"thinking": {"type": "disabled"}},
                    },
                )
            selection = json.loads(raw)
        except Exception as exc:
            return {**base, "error": f"{type(exc).__name__}: {exc}"}
        if not isinstance(selection, dict):
            return {**base, "error": "Final rerank returned non-object JSON."}

        materialized = self._materialize_final_rerank(
            selection,
            recommended_plans=recommended_plans,
        )
        if not materialized["valid"]:
            return {**base, "error": materialized["detail"]}

        primary_plan = materialized["plan"]
        guard_result = self._final_rerank_seed_loss_guard(
            primary_plan,
            recommended_plans[0],
            seed_skill_ids=seed_skill_ids,
        )
        if guard_result["guard_applied"]:
            return {
                **base,
                "guard_applied": True,
                "guard_reason": guard_result["reason"],
                "error": guard_result["reason"],
            }
        output = [primary_plan]
        seen = {_dict_plan_signature(primary_plan)}
        for plan in recommended_plans:
            signature = _dict_plan_signature(plan)
            if signature in seen:
                continue
            output.append(plan)
            seen.add(signature)
            if len(output) >= self.effective_top_k:
                break
        return {
            **base,
            "applied": True,
            "reason": _short_text(str(selection.get("reason") or "")),
            "cross_plan_skill_merge": materialized["cross_plan_skill_merge"],
            "recommended_plans": output,
        }

    def _final_rerank_seed_loss_guard(
        self,
        primary_plan: dict[str, Any],
        original_top_plan: dict[str, Any],
        *,
        seed_skill_ids: tuple[str, ...],
    ) -> dict[str, Any]:
        primary_signals = self._plan_signal_counts(
            primary_plan,
            seed_skill_ids=seed_skill_ids,
        )
        original_signals = self._plan_signal_counts(
            original_top_plan,
            seed_skill_ids=seed_skill_ids,
        )
        loses_seeds = primary_signals["seed_hits"] < original_signals["seed_hits"]
        no_output_compensation = (
            primary_signals["output_hits"] <= original_signals["output_hits"]
        )
        no_graph_compensation = (
            primary_signals["graph_expansion_hits"]
            <= original_signals["graph_expansion_hits"]
        )
        if loses_seeds and no_output_compensation and no_graph_compensation:
            return {
                "guard_applied": True,
                "reason": (
                    "Final rerank rejected because primary plan loses retrieval "
                    "seed coverage without output or graph expansion compensation."
                ),
            }
        return {"guard_applied": False, "reason": ""}

    def _plan_signal_counts(
        self,
        plan: dict[str, Any],
        *,
        seed_skill_ids: tuple[str, ...],
    ) -> dict[str, int]:
        skill_ids = [
            str(step.get("skill_id") or "").strip()
            for step in plan.get("steps") or []
            if isinstance(step, dict) and str(step.get("skill_id") or "").strip()
        ]
        seed_skill_id_set = set(seed_skill_ids)
        produced_types = {
            str(item.get("type") or "").strip().lower()
            for item in plan.get("produced_artifacts") or []
            if isinstance(item, dict)
        }
        return {
            "seed_hits": len(
                {
                    current_skill_id
                    for current_skill_id in skill_ids
                    if current_skill_id in seed_skill_id_set
                }
            ),
            "graph_expansion_hits": len(
                {
                    current_skill_id
                    for current_skill_id in skill_ids
                    if current_skill_id not in seed_skill_id_set
                }
            ),
            "output_hits": len(self.required_output_types & produced_types),
        }

    def _final_rerank_payload(
        self,
        *,
        query: str,
        recommended_plans: list[dict[str, Any]],
        seed_skill_ids: tuple[str, ...],
    ) -> dict[str, Any]:
        return {
            "query": query,
            "retrieval_seed_skill_ids": list(seed_skill_ids),
            "required_output_types": sorted(self.required_output_types),
            "candidate_skill_pool": self._candidate_skill_pool_for_rerank(
                recommended_plans,
                seed_skill_ids=seed_skill_ids,
            ),
            "candidate_plans": [
                self._compact_plan_for_rerank(
                    plan,
                    plan_index=index,
                    seed_skill_ids=seed_skill_ids,
                )
                for index, plan in enumerate(recommended_plans, start=1)
            ],
        }

    def _compact_plan_for_rerank(
        self,
        plan: dict[str, Any],
        *,
        plan_index: int,
        seed_skill_ids: tuple[str, ...],
    ) -> dict[str, Any]:
        skill_ids = [
            str(step.get("skill_id") or "").strip()
            for step in plan.get("steps") or []
            if isinstance(step, dict) and str(step.get("skill_id") or "").strip()
        ]
        produced_types = {
            str(item.get("type") or "").strip().lower()
            for item in plan.get("produced_artifacts") or []
            if isinstance(item, dict)
        }
        return {
            "plan_index": plan_index,
            "skills": skill_ids,
            "seed_hits": [
                current_skill_id
                for current_skill_id in skill_ids
                if current_skill_id in seed_skill_ids
            ],
            "graph_expansion_hits": [
                current_skill_id
                for current_skill_id in skill_ids
                if current_skill_id not in seed_skill_ids
            ],
            "output_hits": sorted(self.required_output_types & produced_types),
            "missing_input_count": len(plan.get("missing_inputs") or []),
            "step_count": len(skill_ids),
            "has_can_feed_edges": bool(plan.get("can_feed_edges") or []),
            "internal_rank": plan_index,
        }

    def _candidate_skill_pool_for_rerank(
        self,
        recommended_plans: list[dict[str, Any]],
        *,
        seed_skill_ids: tuple[str, ...],
    ) -> list[dict[str, Any]]:
        skill_ids = sorted(_candidate_plan_skill_ids(recommended_plans))
        seed_skill_id_set = set(seed_skill_ids)
        output = []
        for current_skill_id in skill_ids:
            skill = self.skill_by_id.get(current_skill_id)
            if not skill:
                continue
            produced_types = sorted(
                {
                    str(item.get("type") or "").strip().lower()
                    for item in skill.get("outputs") or []
                    if isinstance(item, dict)
                    and str(item.get("type") or "").strip()
                }
            )
            output.append(
                {
                    "skill_id": current_skill_id,
                    "name": str(skill.get("name") or current_skill_id),
                    "description": str(skill.get("description") or "")[:240],
                    "is_retrieval_seed": current_skill_id in seed_skill_id_set,
                    "is_graph_expanded": current_skill_id not in seed_skill_id_set,
                    "produced_artifact_types": produced_types,
                }
            )
        return output

    def _materialize_final_rerank(
        self,
        selection: dict[str, Any],
        *,
        recommended_plans: list[dict[str, Any]],
    ) -> dict[str, Any]:
        selected_index = _positive_int(selection.get("selected_plan_index")) or 1
        if selected_index > len(recommended_plans):
            return {
                "valid": False,
                "detail": f"Final rerank selected invalid plan index: {selected_index}",
            }
        allowed_skill_ids = _candidate_plan_skill_ids(recommended_plans)
        raw_steps = selection.get("steps")
        if raw_steps is None:
            return {
                "valid": True,
                "detail": "",
                "cross_plan_skill_merge": False,
                "plan": {
                    **recommended_plans[selected_index - 1],
                    "reason": _short_text(
                        str(selection.get("reason") or "")
                    )
                    or recommended_plans[selected_index - 1].get("reason", ""),
                    "source": "bidirectional_beam_final_rerank",
                },
            }

        step_ids = _normalize_rerank_step_ids(raw_steps)
        if not step_ids:
            return {"valid": False, "detail": "Final rerank returned no steps."}
        unknown = [
            current_skill_id
            for current_skill_id in step_ids
            if current_skill_id not in allowed_skill_ids
            or current_skill_id not in self.skill_by_id
        ]
        if unknown:
            return {
                "valid": False,
                "detail": f"Final rerank selected unknown skill IDs: {unknown}",
            }

        edge_result = _normalize_rerank_edges(selection.get("can_feed_edges") or [])
        selected_edges = edge_result["edges"]
        if not selected_edges and len(step_ids) > 1:
            selected_edges = [
                (step_ids[index], step_ids[index + 1])
                for index in range(len(step_ids) - 1)
            ]
        step_set = set(step_ids)
        outside = [
            edge
            for edge in selected_edges
            if edge[0] not in step_set or edge[1] not in step_set
        ]
        if outside:
            return {
                "valid": False,
                "detail": f"Final rerank selected edges outside steps: {outside}",
            }
        order = {current_skill_id: index for index, current_skill_id in enumerate(step_ids)}
        backward = [
            edge for edge in selected_edges if order[edge[0]] >= order[edge[1]]
        ]
        if backward:
            return {
                "valid": False,
                "detail": f"Final rerank selected backward edges: {backward}",
            }
        selected_plan_skills = set(
            _dict_plan_signature(recommended_plans[selected_index - 1])
        )
        cross_plan_skill_merge = not set(step_ids) <= selected_plan_skills
        return {
            "valid": True,
            "detail": "",
            "cross_plan_skill_merge": cross_plan_skill_merge,
            "plan": self._final_rerank_plan_payload(
                selection,
                step_ids=step_ids,
                selected_edges=selected_edges,
                edge_reasons=edge_result["reasons"],
                recommended_plans=recommended_plans,
            ),
        }

    def _final_rerank_plan_payload(
        self,
        selection: dict[str, Any],
        *,
        step_ids: list[str],
        selected_edges: list[tuple[str, str]],
        edge_reasons: dict[tuple[str, str], str],
        recommended_plans: list[dict[str, Any]],
    ) -> dict[str, Any]:
        missing_by_skill = _missing_inputs_by_skill(recommended_plans)
        step_reason_by_skill = _step_reasons_by_skill(selection.get("steps") or [])
        steps = []
        produced_artifacts = []
        for index, current_skill_id in enumerate(step_ids, start=1):
            skill = self.skill_by_id[current_skill_id]
            outputs = list(skill.get("outputs") or [])
            produced_artifacts.extend(
                {
                    "name": item.get("name"),
                    "type": item.get("type") or "unknown",
                    "source": "skill_output",
                }
                for item in outputs
                if item.get("name")
            )
            steps.append(
                {
                    "step": index,
                    "skill_id": current_skill_id,
                    "name": str(skill.get("name") or current_skill_id),
                    "inputs": list(skill.get("inputs") or []),
                    "outputs": outputs,
                    "missing_inputs": missing_by_skill.get(current_skill_id, []),
                    "filled_inputs": [],
                    "reason": step_reason_by_skill.get(current_skill_id, ""),
                }
            )
        missing_inputs = [
            item for current in step_ids for item in missing_by_skill.get(current, [])
        ]
        edge_by_key = {
            (skill_id(edge.get("source")), skill_id(edge.get("target"))): edge
            for edge in self.eligible_edges
        }
        edge_items = []
        has_inferred_edges = False
        for edge in selected_edges:
            if edge in edge_by_key:
                edge_items.append(edge_plan_item(edge_by_key[edge]))
                continue
            has_inferred_edges = True
            edge_items.append(
                _beam_final_rerank_inferred_edge_item(
                    edge,
                    edge_reasons.get(edge, ""),
                )
            )
        status = "needs_input" if missing_inputs else "ready"
        reason = _short_text(str(selection.get("reason") or ""))
        return {
            "title": default_beam_plan_title(self.language),
            "status": status,
            "steps": steps,
            "stages": [
                {"stage": index, "skills": [step]}
                for index, step in enumerate(steps, start=1)
            ],
            "produced_artifacts": produced_artifacts,
            "missing_inputs": missing_inputs,
            "can_feed_edges": edge_items,
            "reason": reason,
            "reasons": [reason] if reason else [],
            "plan_classification": (
                "executable"
                if status == "ready"
                else "structurally_valid_but_incomplete"
            ),
            "connectivity_trace": (
                ["can_feed", "beam_final_rerank_inferred"]
                if has_inferred_edges
                else (["can_feed"] if edge_items else [])
            ),
            "source": "bidirectional_beam_final_rerank",
        }

    def _client(self) -> Any:
        if self.llm_client is not None:
            return self.llm_client
        if self.llm_config is None:
            raise ValueError(
                "beam Symphony planning requires llm_config or llm_client."
            )
