def _direction_label(directions: list[str]) -> str:
    filtered = [item for item in directions if item and item != "final"]
    if not filtered:
        return ""
    if len(filtered) == 1:
        return filtered[0]
    if "seed" in filtered and len(filtered) == 2:
        return next(item for item in filtered if item != "seed")
    return "mixed"


