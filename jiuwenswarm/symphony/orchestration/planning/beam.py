@dataclass(frozen=True)
class BeamState:
    """One bidirectional beam search state."""

    skill_ids: tuple[str, ...]
    edge_indices: tuple[int, ...]
    available: frozenset[tuple[str, str]]
    judgement_scores: tuple[float, ...]
    score_reasons: tuple[str, ...]
    seed_skill_ids: tuple[str, ...]
    directions: frozenset[str]

    @property
    def depth(self) -> int:
        return len(self.skill_ids)

    @property
    def head(self) -> str:
        return self.skill_ids[0]

    @property
    def tail(self) -> str:
        return self.skill_ids[-1]

    def to_search_state(self) -> SearchState:
        return SearchState(
            skill_ids=self.skill_ids,
            available=self.available,
            edges=self.edge_indices,
            score_reasons=self.score_reasons,
        )


@dataclass(frozen=True)
class NeighborExpansion:
    """A single adjacent Skill candidate to be judged."""

    candidate_id: str
    state: BeamState
    direction: str
    current_skill_id: str
    candidate_skill_id: str
    edge_index: int


@dataclass(frozen=True)
class PlannerJudgement:
    """LLM judgement for one neighbor expansion."""

    candidate_id: str
    score: float
    reason: str


@dataclass(frozen=True)
class SubtreeCacheEntry:
    """Accepted neighbor expansion reusable from the same current Skill."""

    candidate_skill_id: str
    edge_index: int
    judgement_score: float
    reason: str


